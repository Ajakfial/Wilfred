SearchResult glyph_card(const Glyph& g, int score) {
  SearchResult r;
  r.title = std::string(g.ch) + "   " + g.name;
  r.subtitle = g.symbol ? "Symbol · enter copies" : "Emoji · enter copies";
  r.payload = g.ch;
  r.path = g.ch;
  r.action = ResultAction::Copy;
  r.score = score;
  r.kind_label = g.symbol ? "symbol" : "emoji";
  r.category = "mini";
  return r;
}

int score_glyph(std::string_view q, const Glyph& g) {
  if (q.empty()) return 9000;
  auto hay = to_lower_utf8(std::string(g.name) + " " + g.tags + " " + g.ch);
  auto needle = to_lower_utf8(std::string(q));
  if (hay == needle || std::string_view(g.name) == q) return 10000;
  if (hay.find(needle) != std::string::npos) return 9500;
  auto fz = score_fuzzy(needle, hay, g.name);
  if (!fz.matched) return 0;
  return 8000 + fz.score;
}

