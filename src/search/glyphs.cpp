std::vector<SearchResult> glyph_results(std::string_view query, bool symbols) {
  std::string q = std::string(query);
  while (!q.empty() && (q.front() == ' ' || q.front() == '\t'))
    q.erase(q.begin());
  while (!q.empty() && (q.back() == ' ' || q.back() == '\t'))
    q.pop_back();

  struct Hit {
    const Glyph* g;
    int score;
  };
  std::vector<Hit> hits;
  hits.reserve(64);
  for (const auto& g : kGlyphs) {
    if (g.symbol != symbols) continue;
    int sc = score_glyph(q, g);
    if (sc <= 0 && !q.empty()) continue;
    hits.push_back({&g, sc});
  }
  if (q.empty()) {
    if (hits.size() > 24) hits.resize(24);
  } else {
    std::sort(hits.begin(), hits.end(), [](const Hit& a, const Hit& b) {
      if (a.score != b.score) return a.score > b.score;
      return std::string_view(a.g->name) < std::string_view(b.g->name);
    });
    if (hits.size() > 32) hits.resize(32);
  }
  std::vector<SearchResult> out;
  out.reserve(hits.size());
  int n = 0;
  for (auto& h : hits) {
    out.push_back(glyph_card(*h.g, h.score - n));
    ++n;
  }
  if (out.empty()) {
    SearchResult r;
    r.title = symbols ? "No matching symbols" : "No matching emoji";
    r.subtitle = symbols ? "Try arrow, check, copyright, euro" : "Try smile, fire, heart, thumbs";
    r.action = ResultAction::None;
    r.score = 1000;
    r.kind_label = symbols ? "symbol" : "emoji";
    r.category = "mini";
    out.push_back(std::move(r));
  }
  return out;
}

